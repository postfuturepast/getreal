def make_dist_bars_nsw(prices, median):
    brackets = compute_brackets(median)
    total = len(prices)
    if not total:
        return ""
    bars = ""
    for lo, hi, label in brackets:
        count = sum(1 for p in prices if lo <= p < hi)
        pct   = round(100 * count / total)
        width = max(2, pct)
        bars += f"""
    <div class="dist-row">
      <span class="dist-label">{label}</span>
      <div class="dist-track"><div class="dist-bar" style="width:{width}%"></div></div>
      <span class="dist-pct">{pct}%</span>
    </div>"""
    return bars


def make_dist_bars_vic(median):
    brackets = compute_brackets(median)
    sigma = 0.4
    bars = ""
    for lo, hi, label in brackets:
        lo_z = (math.log(max(lo, 1)) - math.log(median)) / sigma if lo > 0 else -4
        hi_z = (math.log(hi) - math.log(median)) / sigma if hi < float('inf') else 4
        phi_lo = 0.5 * (1 + math.erf(lo_z / math.sqrt(2)))
        phi_hi = 0.5 * (1 + math.erf(hi_z / math.sqrt(2)))
        pct   = round(100 * (phi_hi - phi_lo))
        width = max(2, pct)
        bars += f"""
    <div class="dist-row">
      <span class="dist-label">{label}</span>
      <div class="dist-track"><div class="dist-bar" style="width:{width}%"></div></div>
      <span class="dist-pct">~{pct}%</span>
    </div>"""
    return bars


