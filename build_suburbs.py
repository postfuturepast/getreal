# ── Helpers ─────────────────────────────────────────────────────────────────────

def slugify(name):
    return re.sub(r'[^a-z0-9]+', '-', (name or "").lower()).strip('-')


def title_case(s):
    return " ".join(w.capitalize() for w in (s or "").split())


def fmt_price(p):
    if p >= 1_000_000:
        v = p / 1_000_000
        s = f"{v:.2f}".rstrip('0').rstrip('.')
        return f"${s}M"
    if p >= 1_000:
        v = p / 1_000
        s = f"{v:.0f}"
        return f"${s}k"
    return f"${int(p)}"


def fmt_price_full(p):
    return f"${p:,.0f}"


def percentile(sorted_prices, pct):
    if not sorted_prices:
        return 0
    n = len(sorted_prices)
    idx = (n - 1) * pct / 100
    lo = int(idx)
    hi = min(lo + 1, n - 1)
    return int(sorted_prices[lo] * (1 - idx + lo) + sorted_prices[hi] * (idx - lo))


def budget_access(sorted_prices, budget):
    """Percentage of sales at or below budget (NSW — real data)."""
    if not sorted_prices:
        return 0
    count = sum(1 for p in sorted_prices if p <= budget)
    return round(100 * count / len(sorted_prices))


def vic_budget_access(median, budget):
    """Log-normal approximation for VIC (no individual records available)."""
    if median <= 0 or budget <= 0:
        return 0
    sigma = 0.4
    z = (math.log(budget) - math.log(median)) / sigma
    return max(0, min(100, round(50 * (1 + math.erf(z / math.sqrt(2))))))


def get_grade(pct):
    for threshold, letter, label, color, bg in GRADES:
        if pct >= threshold:
            return letter, label, color, bg
    return "D", "Very limited", "#c62828", "#ffebee"


def compute_brackets(median):
    """5 dynamic price brackets centred around median."""
    def snap(v):
        if v < 300_000:   return round(v / 25_000)  * 25_000
        if v < 1_000_000: return round(v / 50_000)  * 50_000
        if v < 3_000_000: return round(v / 100_000) * 100_000
        return round(v / 250_000) * 250_000

    b = [snap(median * r) for r in (0.5, 0.8, 1.2, 1.8)]
    return [
        (0,    b[0], f"Under {fmt_price(b[0])}"),
        (b[0], b[1], f"{fmt_price(b[0])}–{fmt_price(b[1])}"),
        (b[1], b[2], f"{fmt_price(b[1])}–{fmt_price(b[2])}"),
        (b[2], b[3], f"{fmt_price(b[2])}–{fmt_price(b[3])}"),
        (b[3], float('inf'), f"Over {fmt_price(b[3])}"),
    ]


def round_budget(v):
    return max(250_000, round(v / 25_000) * 25_000)


