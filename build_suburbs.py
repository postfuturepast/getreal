def make_budget_rows_nsw(type_stats, primary_type):
    ts = type_stats.get(primary_type, {})
    median = ts.get("median", 0)
    prices = ts.get("prices", [])
    total  = ts.get("count", 0)
    if not prices or not median:
        return ""
    rows = ""
    for ratio in BUDGET_RATIOS:
        budget = round_budget(median * ratio)
        pct    = budget_access(prices, budget)
        est    = round(pct / 100 * total)
        letter, label, color, bg = get_grade(pct)
        rows += f"""
      <tr>
        <td><strong>{fmt_price_full(budget)}</strong></td>
        <td>{pct}%</td>
        <td><span class="grade-chip" style="background:{bg};color:{color};">{letter} — {label}</span></td>
        <td>~{est:,} of {total:,}</td>
      </tr>"""
    return rows


