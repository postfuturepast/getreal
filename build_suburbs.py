def sb_headers():
    return {
        "apikey":        SUPABASE_SECRET,
        "Authorization": f"Bearer {SUPABASE_SECRET}",
    }


def fetch_nsw_sales():
    """Fetch suburb + property_type + sale_price for all NSW rows."""
    records = []
    page    = 1000
    offset  = 0
    print("Fetching NSW property_sales from Supabase...")
    while True:
        url = (f"{SUPABASE_URL}/rest/v1/property_sales"
               f"?select=suburb,property_type,sale_price"
               f"&state=eq.NSW&limit={page}&offset={offset}")
        r = requests.get(url, headers=sb_headers(), timeout=30)
        if r.status_code != 200:
            print(f"  ERROR {r.status_code}: {r.text[:200]}")
            break
        batch = r.json()
        if not batch:
            break
        records.extend(batch)
        offset += len(batch)
        if offset % 50_000 == 0:
            print(f"  {offset:,} rows fetched...")
        if len(batch) < page:
            break
        time.sleep(0.1)
    print(f"  Total: {len(records):,} NSW records")
    return records


def load_or_fetch_nsw(no_fetch=False):
    if no_fetch and os.path.exists(NSW_CACHE):
        print(f"Loading NSW data from {NSW_CACHE}...")
        with open(NSW_CACHE) as f:
            return json.load(f)
    if not SUPABASE_SECRET:
        if os.path.exists(NSW_CACHE):
            print(f"No SUPABASE_SECRET — using {NSW_CACHE}")
            with open(NSW_CACHE) as f:
                return json.load(f)
        print("ERROR: SUPABASE_SECRET not set and no cache file found.")
        sys.exit(1)
    records = fetch_nsw_sales()
    with open(NSW_CACHE, "w") as f:
        json.dump(records, f)
    print(f"  Cached to {NSW_CACHE}")
    return records


# ── NSW stats ────────────────────────────────────────────────────────────────────

def compute_nsw_stats(records, min_sales=10):
    """Aggregate raw sale records into per-suburb stats."""
    by = defaultdict(lambda: defaultdict(list))
    for r in records:
        suburb = (r.get("suburb") or "").strip().lower()
        ptype  = (r.get("property_type") or "").strip().lower()
        price  = r.get("sale_price") or 0
        if suburb and ptype and price > 50_000:
            by[suburb][ptype].append(price)

    stats = {}
    for suburb, types in by.items():
        total = sum(len(v) for v in types.values())
        if total < min_sales:
            continue
        type_stats = {}
        for ptype, prices in types.items():
            if len(prices) < 3:
                continue
            sp = sorted(prices)
            type_stats[ptype] = {
                "count":  len(sp),
                "median": percentile(sp, 50),
                "p10":    percentile(sp, 10),
                "p25":    percentile(sp, 25),
                "p75":    percentile(sp, 75),
                "p90":    percentile(sp, 90),
                "prices": sp,
            }
        if type_stats:
            stats[suburb] = {"state": "NSW", "types": type_stats, "total": total}

    print(f"  NSW suburbs with {min_sales}+ sales: {len(stats):,}")
    return stats


# ── VIC stats ────────────────────────────────────────────────────────────────────

def load_vic_stats(min_sales=10):
    if not os.path.exists(VIC_JSON):
        print(f"Warning: {VIC_JSON} not found — no VIC pages will be generated")
        return {}
    with open(VIC_JSON) as f:
        data = json.load(f)
    suburbs = data.get("suburbs", {})
    stats = {}
    for suburb, info in suburbs.items():
        if info.get("state") != "VIC":
            continue
        types = {}
        for ptype, td in (info.get("types") or {}).items():
            ann = td.get("annualSales", 0)
            med = td.get("median", 0)
            if ann >= 3 and med > 0:
                types[ptype] = {"count": ann, "median": med}
        if not types:
            continue
        total = sum(t["count"] for t in types.values())
        if total < min_sales:
            continue
        stats[suburb] = {"state": "VIC", "types": types, "total": total}
    print(f"  VIC suburbs with {min_sales}+ annual sales: {len(stats):,}")
    return stats


