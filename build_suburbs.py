"""
build_suburbs.py — GetReal suburb page generator
=================================================
Generates static HTML pages for NSW and VIC suburbs.

NSW: fetches suburb + property_type + sale_price from Supabase property_sales.
     Computes real medians, percentiles, and price distributions.
     Caches raw data to _nsw_suburb_cache.json (reuse with --no-fetch).

VIC: reads suburb-data.json (generated by load_vic_quarterly.py).
     Shows median + annual sales. Budget access estimated via log-normal.

Output:
  suburbs/nsw/{slug}.html     — one per NSW suburb (10+ total sales)
  suburbs/vic/{slug}.html     — one per VIC suburb (10+ annual sales)
  suburbs/nsw/index.html      — NSW suburb listing
  suburbs/vic/index.html      — VIC suburb listing
  suburbs/index.html          — combined index
  sitemap-suburbs.xml         — suburb sitemap (linked from sitemap.xml)

Usage:
  export SUPABASE_SECRET=your_secret_key_here
  python3 build_suburbs.py

Options:
  --no-fetch   Skip Supabase fetch, use _nsw_suburb_cache.json
  --state      Only build 'nsw' or 'vic'
  --min-sales  Minimum total sales (default: 10)
  --limit      Only build first N pages per state (for testing)
  --dry-run    Compute stats and report counts without writing HTML
"""

