# ── Sitemap ──────────────────────────────────────────────────────────────────────

def write_sitemap(nsw_slugs, vic_slugs):
    urls = []
    for slug in nsw_slugs:
        urls.append(f"  <url><loc>{BASE_URL}/suburbs/nsw/{slug}</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>0.6</priority></url>")
    for slug in vic_slugs:
        urls.append(f"  <url><loc>{BASE_URL}/suburbs/vic/{slug}</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>0.6</priority></url>")
    urls.append(f"  <url><loc>{BASE_URL}/suburbs/</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>")
    urls.append(f"  <url><loc>{BASE_URL}/suburbs/nsw/</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>")
    urls.append(f"  <url><loc>{BASE_URL}/suburbs/vic/</loc><lastmod>{TODAY}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>")

    xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    xml += "\n".join(urls)
    xml += "\n</urlset>"
    with open("sitemap-suburbs.xml", "w") as f:
        f.write(xml)
    print(f"  sitemap-suburbs.xml written ({len(nsw_slugs) + len(vic_slugs):,} suburb URLs)")


# ── Main ─────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-fetch",  action="store_true", help="Use cached NSW data")
    parser.add_argument("--state",     choices=["nsw", "vic"], help="Only build one state")
    parser.add_argument("--min-sales", type=int, default=MIN_SALES)
    parser.add_argument("--limit",     type=int, default=0, help="Max pages per state (0=all)")
    parser.add_argument("--dry-run",   action="store_true", help="Stats only, no HTML written")
    args = parser.parse_args()

    # ── Load data ──────────────────────────────────────────────────────────────
    nsw_stats = {}
    vic_stats = {}

    if not args.state or args.state == "nsw":
        raw = load_or_fetch_nsw(no_fetch=args.no_fetch)
        nsw_stats = compute_nsw_stats(raw, min_sales=args.min_sales)

    if not args.state or args.state == "vic":
        vic_stats = load_vic_stats(min_sales=args.min_sales)

    total_pages = (len(nsw_stats) if not args.state or args.state == "nsw" else 0) + \
                  (len(vic_stats) if not args.state or args.state == "vic" else 0)
    print(f"\nTotal suburb pages to generate: {total_pages:,}")

    if args.dry_run:
        print("[DRY RUN] No files written.")
        return

    # ── Create output dirs ────────────────────────────────────────────────────
    (OUT_DIR / "nsw").mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "vic").mkdir(parents=True, exist_ok=True)

    # ── Generate NSW pages ────────────────────────────────────────────────────
    nsw_slugs = []
    if nsw_stats:
        suburbs = list(nsw_stats.items())
        if args.limit:
            suburbs = suburbs[:args.limit]
        print(f"\nGenerating {len(suburbs):,} NSW suburb pages...")
        for i, (suburb, info) in enumerate(suburbs):
            slug = slugify(suburb)
            html = generate_suburb_page(suburb, "NSW", info["types"], info["total"])
            path = OUT_DIR / "nsw" / f"{slug}.html"
            path.write_text(html, encoding="utf-8")
            nsw_slugs.append(slug)
            if (i + 1) % 500 == 0:
                print(f"  {i+1:,} NSW pages written...")
        print(f"  {len(nsw_slugs):,} NSW pages complete")

        idx = generate_state_index("NSW", nsw_stats if not args.limit else dict(list(nsw_stats.items())[:args.limit]))
        (OUT_DIR / "nsw" / "index.html").write_text(idx, encoding="utf-8")

    # ── Generate VIC pages ────────────────────────────────────────────────────
    vic_slugs = []
    if vic_stats:
        suburbs = list(vic_stats.items())
        if args.limit:
            suburbs = suburbs[:args.limit]
        print(f"\nGenerating {len(suburbs):,} VIC suburb pages...")
        for i, (suburb, info) in enumerate(suburbs):
            slug = slugify(suburb)
            html = generate_suburb_page(suburb, "VIC", info["types"], info["total"])
            path = OUT_DIR / "vic" / f"{slug}.html"
            path.write_text(html, encoding="utf-8")
            vic_slugs.append(slug)
            if (i + 1) % 500 == 0:
                print(f"  {i+1:,} VIC pages written...")
        print(f"  {len(vic_slugs):,} VIC pages complete")

        idx = generate_state_index("VIC", vic_stats if not args.limit else dict(list(vic_stats.items())[:args.limit]))
        (OUT_DIR / "vic" / "index.html").write_text(idx, encoding="utf-8")

    # ── Combined index ────────────────────────────────────────────────────────
    combined = generate_combined_index(len(nsw_slugs), len(vic_slugs))
    (OUT_DIR / "index.html").write_text(combined, encoding="utf-8")

    # ── Sitemap ───────────────────────────────────────────────────────────────
    print("\nWriting sitemap-suburbs.xml...")
    write_sitemap(nsw_slugs, vic_slugs)

    print(f"\n{'='*60}")
    print(f"DONE")
    print(f"{'='*60}")
    print(f"NSW pages:  {len(nsw_slugs):,}")
    print(f"VIC pages:  {len(vic_slugs):,}")
    print(f"Total:      {len(nsw_slugs) + len(vic_slugs):,}")
    print(f"\nDeploy: git add suburbs/ sitemap-suburbs.xml && git commit -m 'Add suburb pages' && git push")


if __name__ == "__main__":
    main()
